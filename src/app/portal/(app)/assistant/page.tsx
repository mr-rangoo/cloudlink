import type { Metadata } from "next";
import Link from "next/link";
import { getCustomerContext } from "@/server/portal/page";
import { customerAssistant } from "@/server/assistant/service";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/feedback";
import { AssistantChat, type ChatMessage } from "./chat";

export const metadata: Metadata = { title: "Assistant · Customer portal" };

export default async function PortalAssistant() {
  const ctx = await getCustomerContext();
  const a = await customerAssistant(ctx);
  if (!a.enabled) {
    return (
      <Card>
        <CardContent className="space-y-2 py-6 text-sm">
          <h1 className="text-lg font-semibold">Assistant unavailable</h1>
          <p className="text-muted-foreground">
            Chat is not available right now.{" "}
            <Link href="/portal/tickets/new" className="text-accent hover:underline">
              Open a support request
            </Link>{" "}
            and our team will get back to you.
          </p>
        </CardContent>
      </Card>
    );
  }
  return (
    <div className="space-y-3">
      <div className="space-y-1">
        <h1 className="flex flex-wrap items-center gap-2 text-xl font-semibold">
          {a.name} {a.simulated ? <Badge tone="warning">Test mode</Badge> : null}
        </h1>
        <p className="text-xs text-muted-foreground">
          {a.name} is an AI assistant. It looks up your account to answer questions and can make mistakes, so check amounts on your invoices. It cannot take payments or change your service. Chats are saved and can be read by {ctx.organization.name} staff.
          {a.simulated ? " Test mode: replies are generated by simple rules, not an AI service." : ""}
        </p>
      </div>
      <Card className="overflow-hidden">
        <AssistantChat name={a.name} conversationId={a.conversation?.id ?? null} initial={(a.conversation?.messages ?? []).map((m) => ({ id: m.id, role: m.role as ChatMessage["role"], text: m.text, tools: m.tools }))} />
      </Card>
    </div>
  );
}
