"use client";

import * as React from "react";
import Link from "next/link";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Field, Input, Textarea } from "@/components/ui/form";
import { Alert, Badge } from "@/components/ui/feedback";
import { useMutation } from "@/components/use-mutation";

interface Status {
  adapter: "anthropic" | "mock" | "disabled";
  model: string | null;
}

export function AssistantForm({ initial, status, organizationName }: { initial: { enabled: boolean; name: string; instructions: string | null }; status: Status; organizationName: string }) {
  const { mutate, pending, errors, formError } = useMutation();
  const [enabled, setEnabled] = React.useState(initial.enabled);
  const onSubmit = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    const data = new FormData(e.currentTarget);
    await mutate("/settings/assistant", { method: "PUT", body: { enabled, name: String(data.get("name") ?? ""), instructions: String(data.get("instructions") ?? "") } }, { success: "Assistant settings saved" });
  };
  return (
    <form onSubmit={onSubmit} className="space-y-4" noValidate>
      <Card>
        <CardHeader>
          <CardTitle>AI assistant</CardTitle>
          <CardDescription>A chat assistant in the customer portal that answers questions about each customer&apos;s own balance, invoices, payments and connection, explains how to pay, and opens a support ticket when a person is needed.</CardDescription>
        </CardHeader>
        <CardContent className="space-y-4">
          {status.adapter === "anthropic" ? (
            <Alert tone="info" title="Connected to Claude">
              Replies are generated by {status.model} (Anthropic). Each customer question, with the account details needed to answer it, is sent to Anthropic for processing.
            </Alert>
          ) : status.adapter === "mock" ? (
            <Alert tone="warning" title="Test mode">
              Replies come from simple built-in rules using real account data. No AI service is called. Set ASSISTANT_ADAPTER=anthropic and ANTHROPIC_API_KEY to use Claude.
            </Alert>
          ) : (
            <Alert tone="warning" title="Not configured for this deployment">
              Customers will not see the assistant until the server sets ASSISTANT_ADAPTER=anthropic and ANTHROPIC_API_KEY.
            </Alert>
          )}
          {formError ? <Alert tone="danger">{formError}</Alert> : null}
          <label className="flex items-start gap-3 text-sm">
            <input type="checkbox" checked={enabled} onChange={(e) => setEnabled(e.target.checked)} className="mt-0.5" />
            <span>
              <span className="font-medium">Show the assistant to customers</span> {enabled ? <Badge tone="success">On</Badge> : <Badge tone="neutral">Off</Badge>}
              <span className="block text-muted-foreground">Customers can see their own records only. It cannot take payments, change services or promise refunds.</span>
            </span>
          </label>
          <Field id="as-name" label="Assistant name" hint="Shown to customers, e.g. “Nuru” or “Skyline Help”" error={errors.name} required>
            <Input name="name" defaultValue={initial.name} maxLength={40} />
          </Field>
          <Field id="as-ins" label="Extra guidance (optional)" hint={`Facts and tone for ${organizationName}: office hours, outage notices, what to say about installations. Up to 1500 characters.`} error={errors.instructions}>
            <Textarea name="instructions" defaultValue={initial.instructions ?? ""} maxLength={1500} rows={5} />
          </Field>
          <p className="text-xs text-muted-foreground">
            Chats are kept for 180 days and are listed under{" "}
            <Link href="/support/assistant" className="text-accent hover:underline">
              Support → Assistant chats
            </Link>
            . Customers are told they are chatting with an AI and that staff can read the chat.
          </p>
        </CardContent>
      </Card>
      <div className="flex justify-end">
        <Button type="submit" loading={pending}>
          Save assistant settings
        </Button>
      </div>
    </form>
  );
}
