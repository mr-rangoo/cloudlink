/**
 * Accept only same-origin relative paths for post-login redirects. Rejects absolute URLs, protocol-relative
 * ("//host"), backslash tricks ("/\host", which browsers treat as "//host") and control characters.
 */
export function safeRedirectPath(value: string | null | undefined, fallback = "/dashboard"): string {
  if (!value || !value.startsWith("/") || value.startsWith("//") || value.includes("\\") || /[\u0000-\u001f\u007f]/.test(value)) return fallback;
  try {
    const base = "http://cloudlink.invalid";
    const url = new URL(value, base);
    if (url.origin !== base) return fallback;
    return `${url.pathname}${url.search}${url.hash}`;
  } catch {
    return fallback;
  }
}
