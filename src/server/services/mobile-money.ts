async function scheduleQuery(attempt: Pick<PaymentAttempt, "id" | "organizationId">, delayMs = QUERY_DELAY_MS, suffix = "auto") {
  const op = await enqueueOperation({
    type: "payments.mpesa.query",
    organizationId: attempt.organizationId,
    payload: { attemptId: attempt.id },
    dedupeKey: `payments.mpesa.query:${attempt.id}:${suffix}`,
    runAfter: new Date(Date.now() + delayMs),
    maxAttempts: QUERY_MAX_ATTEMPTS,
  });
  await dispatchOperation(op);
}

/**
 * Ask M-Pesa to prompt the payer's phone (STK Push). Returns the attempt; its final state arrives by callback.
 * Idempotent per (organization, idempotency key).
 */
export async function initiateStkPush(ctx: ActorContext, raw: z.input<typeof stkPushInput>, opts: { channel: "staff" | "portal"; idempotencyKey: string }) {
  const input = stkPushInput.parse(raw);
  if (ctx.kind === "staff") requirePermission(ctx, "payments.initiate");
  if (ctx.kind === "customer" && ctx.subscriberId !== input.subscriberId) throw notFound("subscriber");
  const subscriber = await db.subscriber.findFirst({
    where: { id: input.subscriberId, organizationId: ctx.organizationId, ...(ctx.kind === "staff" ? tenantWhere(ctx) : {}) },
    select: { id: true, accountNumber: true, branchId: true, status: true },
  });
  if (!subscriber) throw notFound("subscriber");
  const org = await db.organization.findUniqueOrThrow({ where: { id: ctx.organizationId }, select: { currency: true } });
  if (org.currency !== "KES") throw new AppError("INVALID_STATE", "M-Pesa payments are only available for KES accounts.");
  const phone = toMsisdn(input.phone);
  if (!phone) throw new AppError("VALIDATION_ERROR", "Enter a Safaricom number such as 0712 345 678.", { fields: [{ path: "phone", message: "Not an M-Pesa number" }] });
  if (input.invoiceId) {
    const invoice = await db.invoice.findFirst({ where: { id: input.invoiceId, organizationId: ctx.organizationId, subscriberId: subscriber.id }, select: { status: true, balanceDue: true } });
    if (!invoice) throw notFound("invoice");
    if (invoice.status !== "OPEN" && invoice.status !== "PARTIALLY_PAID") throw new AppError("INVALID_STATE", "This invoice has nothing left to pay.");
    const ceiling = new D(invoice.balanceDue.toString()).ceil();
    if (new D(input.amount).gt(ceiling)) throw new AppError("VALIDATION_ERROR", `The invoice balance is ${ceiling.toFixed(0)}. Pay that amount or less.`, { fields: [{ path: "amount", message: "More than the invoice balance" }] });
  }

  const key = `${opts.channel}:${opts.idempotencyKey}`;
  const existing = await db.paymentAttempt.findUnique({ where: { organizationId_idempotencyKey: { organizationId: ctx.organizationId, idempotencyKey: key } } });
  if (existing) return publicAttempt(existing);

  await consumeRateLimit(RATE_LIMITS.paymentInitiation, `${ctx.organizationId}:phone:${phone}`);
  await consumeRateLimit(RATE_LIMITS.paymentInitiation, `${ctx.organizationId}:subscriber:${subscriber.id}`);
  const gw = await resolveGateway(ctx.organizationId);
  const token = randomToken(24);
  let attempt = await db.paymentAttempt
    .create({
      data: {
        organizationId: ctx.organizationId,
        subscriberId: subscriber.id,
        invoiceId: input.invoiceId ?? null,
        provider: gw.provider,
        channel: opts.channel,
        amount: String(input.amount),
        currency: org.currency,
        phone,
        accountReference: stkReference(subscriber.accountNumber),
        idempotencyKey: key,
        callbackTokenHash: sha256(token),
        requestedById: ctx.kind === "staff" ? ctx.userId : null,
        requestedBy: ctx.kind === "staff" ? "user" : ctx.kind === "customer" ? "customer" : "system",
        detail: "Sending the request to M-Pesa",
        metadata: { environment: gw.environment },
      },
    })
    .catch(async (err) => {
      if ((err as { code?: string }).code === "P2002") return db.paymentAttempt.findUniqueOrThrow({ where: { organizationId_idempotencyKey: { organizationId: ctx.organizationId, idempotencyKey: key } } });
      throw err;
    });
  if (attempt.status !== "PENDING" || attempt.checkoutRequestId) return publicAttempt(attempt);

  const callbackUrl = `${callbackBaseUrl()}/api/v1/webhooks/mobile-money/stk/${token}`;
  try {
    const res = await gw.gateway.requestPayment({ amount: input.amount, phone, accountReference: attempt.accountReference, description: "Internet", callbackUrl });
    attempt = await db.paymentAttempt.update({
      where: { id: attempt.id },
      data: {
        status: "SUBMITTED",
        merchantRequestId: res.merchantRequestId,
        checkoutRequestId: res.checkoutRequestId,
        submittedAt: new Date(),
        detail: gw.provider === "mock" ? "Simulated request: no prompt was sent. Use “Simulate customer response” to continue." : "Waiting for the customer to enter their M-Pesa PIN",
      },
    });
    await scheduleQuery(attempt);
  } catch (err) {
    if (err instanceof PermanentError) {
      attempt = await db.paymentAttempt.update({ where: { id: attempt.id }, data: { status: "FAILED", resultDesc: err.code, detail: err.message, completedAt: new Date() } });
    } else {
      // The provider may or may not have sent the prompt. Never guess: keep it open; a callback on the
      // attempt's secret URL can still confirm it, otherwise it surfaces for reconciliation.
      const message = err instanceof RetryableError ? err.message : "Unexpected error";
      attempt = await db.paymentAttempt.update({
        where: { id: attempt.id },
        data: { status: "UNKNOWN", resultDesc: err instanceof RetryableError ? err.code : "UNEXPECTED", detail: `${message}. If the customer received a prompt and paid, the payment is recorded when M-Pesa reports it.` },
      });
      if (!(err instanceof RetryableError)) logger.error({ attemptId: attempt.id, err: err instanceof Error ? err.name : "unknown" }, "unexpected error requesting STK push");
    }
  }
  if (ctx.kind === "staff") {
    await audit(ctx, { action: "payment.mpesa.request", entityType: "payment_attempt", entityId: attempt.id, metadata: { subscriberId: subscriber.id, invoiceId: input.invoiceId ?? null, amount: attempt.amount.toString(), phone: maskMsisdn(phone), status: attempt.status } });
  }
  return publicAttempt(attempt);
}

/** Portal: the signed-in customer pays (part of) their own balance or one of their own invoices. */
export async function initiateCustomerPayment(ctx: CustomerContext, raw: z.input<typeof customerPaymentInput>) {
  const input = customerPaymentInput.parse(raw);
  return initiateStkPush(ctx, { subscriberId: ctx.subscriberId, invoiceId: input.invoiceId ?? null, phone: input.phone, amount: input.amount }, { channel: "portal", idempotencyKey: input.requestId });
}

