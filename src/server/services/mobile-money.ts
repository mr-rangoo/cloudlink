/** Optional source allowlist (MPESA_CALLBACK_ALLOWED_IPS). Relies on the first X-Forwarded-For hop set by your proxy. */
export function callbackSourceAllowed(ip: string | null): boolean {
  const list = (process.env.MPESA_CALLBACK_ALLOWED_IPS ?? "").split(",").map((s) => s.trim()).filter(Boolean);
  if (!list.length) return true;
  if (!ip || !net.isIP(ip)) return false;
  const family = net.isIP(ip) === 4 ? "ipv4" : "ipv6";
  const block = new net.BlockList();
  for (const entry of list) {
    const [addr, prefix] = entry.split("/");
    const fam = net.isIP(addr ?? "") === 6 ? "ipv6" : "ipv4";
    if (!addr || !net.isIP(addr)) continue;
    if (prefix) block.addSubnet(addr, Number(prefix), fam);
    else block.addAddress(addr, fam);
  }
  return block.check(ip, family);
}

function parseJson(raw: string): unknown {
  try {
    return JSON.parse(raw);
  } catch {
    return undefined;
  }
}

/**
 * Store an event exactly once per (provider, kind, key). An identical repeat is counted and reported as a duplicate.
 * A repeat with a DIFFERENT body is flagged on the original and stored as its own variant, so a forged first
 * arrival can never shadow the genuine one; each variant is then judged on its own (with provider verification).
 */
async function storeEvent(data: { organizationId: string | null; provider: string; kind: string; eventKey: string; fingerprint: string; payload: Prisma.InputJsonValue; attemptId?: string | null; sourceIp: string | null; status?: "RECEIVED" | "REJECTED"; error?: string }): Promise<{ event: WebhookEvent; duplicate: boolean }> {
  const tryInsert = (eventKey: string) =>
    db.webhookEvent.create({ data: { ...data, eventKey, attemptId: data.attemptId ?? null, status: data.status ?? "RECEIVED", error: data.error ?? null } }).catch((err) => {
      if ((err as { code?: string }).code === "P2002") return null;
      throw err;
    });
  const countRepeat = async (eventKey: string) => {
    const row = await db.webhookEvent.findUniqueOrThrow({ where: { provider_kind_eventKey: { provider: data.provider, kind: data.kind, eventKey } } });
    return db.webhookEvent.update({ where: { id: row.id }, data: { duplicateCount: { increment: 1 } } });
  };
  const inserted = await tryInsert(data.eventKey);
  if (inserted) return { event: inserted, duplicate: false };
  const original = await db.webhookEvent.findUniqueOrThrow({ where: { provider_kind_eventKey: { provider: data.provider, kind: data.kind, eventKey: data.eventKey } } });
  if (original.fingerprint === data.fingerprint) return { event: await countRepeat(data.eventKey), duplicate: true };
  await db.webhookEvent.update({ where: { id: original.id }, data: { conflictingDuplicate: true, duplicateCount: { increment: 1 } } });
  logger.warn({ eventId: original.id, kind: data.kind }, "webhook repeat with a different body (possible tampering); stored separately");
  const variantKey = `${data.eventKey}#${data.fingerprint.slice(0, 16)}`;
  const variant = await tryInsert(variantKey);
  if (variant) return { event: variant, duplicate: false };
  return { event: await countRepeat(variantKey), duplicate: true };
}

async function finishEvent(eventId: string, status: "PROCESSED" | "REJECTED" | "FAILED", extra: { error?: string; paymentId?: string | null } = {}) {
  await db.webhookEvent.update({ where: { id: eventId }, data: { status, processedAt: new Date(), ...(extra.error !== undefined ? { error: extra.error.slice(0, 500) } : {}), ...(extra.paymentId ? { paymentId: extra.paymentId } : {}) } });
}

/** POST /webhooks/mobile-money/stk/:token */
export async function handleStkCallbackRequest(token: string, rawBody: string, meta: WebhookMeta): Promise<WebhookResponse> {
  if (!/^[A-Za-z0-9_-]{20,100}$/.test(token)) return { status: 404, body: { error: "Not found" } };
  if (!callbackSourceAllowed(meta.ipAddress)) {
    logger.warn({ correlationId: meta.correlationId, ip: meta.ipAddress }, "stk callback from a source outside MPESA_CALLBACK_ALLOWED_IPS");
    return { status: 403, body: { error: "Forbidden" } };
  }
  await consumeRateLimit(RATE_LIMITS.webhook, `stk:${meta.ipAddress ?? "unknown"}`);
  if (Buffer.byteLength(rawBody) > MAX_WEBHOOK_BYTES) return { status: 413, body: { error: "Too large" } };
  const attempt = await db.paymentAttempt.findUnique({ where: { callbackTokenHash: sha256(token) } });
  if (!attempt) {
    logger.warn({ correlationId: meta.correlationId }, "stk callback for an unknown token");
    return { status: 404, body: { error: "Not found" } };
  }
  return ingestStkCallback(attempt, rawBody, meta);
}

/** Validate structure, store durably (deduplicated), then process. Also used by the mock simulation. */
export async function ingestStkCallback(attempt: PaymentAttempt, rawBody: string, meta: WebhookMeta): Promise<WebhookResponse> {
  const fingerprint = sha256(rawBody);
  const parsed = stkCallbackSchema.safeParse(parseJson(rawBody));
  if (!parsed.success) {
    await storeEvent({ organizationId: attempt.organizationId, provider: attempt.provider, kind: "stk_callback", eventKey: `invalid:${fingerprint}`, fingerprint, payload: { invalid: true }, attemptId: attempt.id, sourceIp: meta.ipAddress, status: "REJECTED", error: "Malformed callback body" });
    return { status: 400, body: { ResultCode: 1, ResultDesc: "Rejected" } };
  }
  const cb = parsed.data.Body.stkCallback;
  const success = stkOutcome(cb.ResultCode) === "SUCCESS" ? stkSuccessDetails(cb) : null;
  // Minimised payload: no full phone number; enough to re-run verification and confirmation.
  const payload = {
    merchantRequestId: cb.MerchantRequestID,
    checkoutRequestId: cb.CheckoutRequestID,
    resultCode: String(cb.ResultCode),
    resultDesc: cb.ResultDesc.slice(0, 200),
    ...(success
      ? { amount: success.amount, receipt: success.receipt, transactionDate: success.transactionDate?.toISOString() ?? null, phoneMatches: success.phone ? success.phone.slice(-9) === attempt.phone.slice(-9) : null }
      : {}),
  };
  // Keyed by request AND CheckoutRequestID: a callback posted on another request's URL can never shadow this one.
  const { event, duplicate } = await storeEvent({ organizationId: attempt.organizationId, provider: attempt.provider, kind: "stk_callback", eventKey: `${attempt.id}:${cb.CheckoutRequestID}`, fingerprint, payload, attemptId: attempt.id, sourceIp: meta.ipAddress });
  if (duplicate && (event.status === "PROCESSED" || event.status === "REJECTED")) return { status: 200, body: ACK };
  try {
    await processStkEvent(event.id);
  } catch (err) {
    if (err instanceof RetryableError) {
      // Durably stored: verify again later; the provider is acknowledged now.
      await db.webhookEvent.update({ where: { id: event.id }, data: { error: err.message.slice(0, 500) } });
      const op = await enqueueOperation({ type: "payments.mpesa.verify", organizationId: attempt.organizationId, payload: { eventId: event.id }, dedupeKey: `payments.mpesa.verify:${event.id}`, maxAttempts: 8 });
      await dispatchOperation(op);
    } else {
      logger.error({ eventId: event.id, err: err instanceof Error ? err.name : "unknown" }, "stk callback processing failed");
      await finishEvent(event.id, "FAILED", { error: err instanceof Error ? err.message : "Processing failed" });
      const op = await enqueueOperation({ type: "payments.mpesa.verify", organizationId: attempt.organizationId, payload: { eventId: event.id }, dedupeKey: `payments.mpesa.verify:${event.id}`, maxAttempts: 8 });
      await dispatchOperation(op);
    }
  }
  return { status: 200, body: ACK };
}

interface StoredStkPayload {
  merchantRequestId: string;
  checkoutRequestId: string;
  resultCode: string;
  resultDesc: string;
  amount?: number;
  receipt?: string;
  transactionDate?: string | null;
  phoneMatches?: boolean | null;
}

async function setAttemptOutcome(attemptId: string, outcome: "FAILED" | "CANCELLED" | "EXPIRED" | "UNKNOWN", data: { resultCode?: string | null; resultDesc?: string; detail: string }) {
  // A confirmed attempt never moves back; money already recorded stays recorded.
  await db.paymentAttempt.updateMany({
    where: { id: attemptId, status: { not: "CONFIRMED" } },
    data: { status: outcome, resultCode: data.resultCode ?? undefined, resultDesc: data.resultDesc?.slice(0, 200), detail: data.detail.slice(0, 500), completedAt: outcome === "UNKNOWN" ? undefined : new Date() },
  });
}

/**
 * Validate the stored callback against the attempt and verify its outcome with the provider (when enabled), then
 * apply it: success records the money; failure/cancellation/expiry is recorded only if the provider agrees.
 * Throws RetryableError when verification must be retried later.
 */
export async function processStkEvent(eventId: string, opts: { final?: boolean } = {}): Promise<void> {
  const event = await db.webhookEvent.findUniqueOrThrow({ where: { id: eventId } });
  if (event.status === "PROCESSED" || event.status === "REJECTED") return;
  if (!event.attemptId) return finishEvent(event.id, "REJECTED", { error: "No payment request" });
  const attempt = await db.paymentAttempt.findUniqueOrThrow({ where: { id: event.attemptId } });
  const p = event.payload as unknown as StoredStkPayload;
  const log = logger.child({ attemptId: attempt.id, eventId: event.id, organizationId: attempt.organizationId });

  if ((attempt.checkoutRequestId && attempt.checkoutRequestId !== p.checkoutRequestId) || (attempt.merchantRequestId && attempt.merchantRequestId !== p.merchantRequestId)) {
    log.warn("stk callback identifiers do not match the payment request");
    return finishEvent(event.id, "REJECTED", { error: "Callback identifiers do not match this payment request" });
  }
  const reported = stkOutcome(p.resultCode);
  if (reported === "SUCCESS") {
    if (!p.receipt || p.amount === undefined) {
      await setAttemptOutcome(attempt.id, "UNKNOWN", { resultCode: p.resultCode, detail: "M-Pesa reported success without a receipt number. Check the M-Pesa statement before recording anything." });
      return finishEvent(event.id, "REJECTED", { error: "Success callback without receipt or amount" });
    }
    if (!new D(p.amount).equals(new D(attempt.amount.toString()))) {
      log.warn({ reported: p.amount, requested: attempt.amount.toString() }, "stk callback amount does not match the request");
      await setAttemptOutcome(attempt.id, "UNKNOWN", { resultCode: p.resultCode, detail: `M-Pesa reported ${p.amount} but ${attempt.amount.toString()} was requested. Review against the M-Pesa statement.` });
      return finishEvent(event.id, "REJECTED", { error: "Amount does not match the request" });
    }
    if (attempt.status === "CONFIRMED" && attempt.providerReceipt && attempt.providerReceipt !== p.receipt) {
      log.warn("a second, different receipt was reported for an already confirmed request");
      return finishEvent(event.id, "REJECTED", { error: "A different receipt was already recorded for this request" });
    }
  }

  // Provider verification: the status query is authoritative; a callback alone never changes the outcome.
  let outcome = reported;
  let resultCode: string | null = p.resultCode;
  let resultDesc = p.resultDesc;
  if (process.env.MPESA_VERIFY_CALLBACKS !== "false") {
    const gw = await resolveGateway(attempt.organizationId).catch((err) => {
      throw new RetryableError(err instanceof Error ? err.message : "Gateway unavailable", "GATEWAY_UNAVAILABLE");
    });
    const mockResultCode = ((attempt.metadata ?? {}) as { mockResultCode?: string }).mockResultCode ?? null;
    const q = await gw.gateway.queryPayment(p.checkoutRequestId, { mockResultCode, createdAt: attempt.createdAt });
    await db.paymentAttempt.update({ where: { id: attempt.id }, data: { lastQueriedAt: new Date(), queryCount: { increment: 1 } } });
    if (q.outcome === "PENDING") {
      if (opts.final) {
        await setAttemptOutcome(attempt.id, "UNKNOWN", { detail: "M-Pesa could not confirm the outcome in time. Check the M-Pesa statement." });
        return finishEvent(event.id, "FAILED", { error: "Verification did not complete" });
      }
      throw new RetryableError("M-Pesa has not finished processing; verifying again shortly", "VERIFY_PENDING");
    }
    if (reported === "SUCCESS" && q.outcome !== "SUCCESS") {
      log.warn({ queryResult: q.resultCode }, "stk success callback contradicted by the provider status query");
      await setAttemptOutcome(attempt.id, q.outcome, { resultCode: q.resultCode, resultDesc: q.resultDesc, detail: stkMessage(q.resultCode ?? "", q.resultDesc) });
      return finishEvent(event.id, "REJECTED", { error: `Provider status query reported ${q.outcome.toLowerCase()} for a success callback` });
    }
    if (reported !== "SUCCESS" && q.outcome === "SUCCESS") {
      // Money moved: do not mark the request failed. The genuine success callback (or reconciliation) settles it.
      log.warn("stk failure callback contradicted by the provider status query (it reports success)");
      await db.paymentAttempt.updateMany({ where: { id: attempt.id, status: { not: "CONFIRMED" } }, data: { status: "SUBMITTED", detail: "M-Pesa reports success; waiting for the confirmation with the receipt number." } });
      await scheduleQuery(attempt, QUERY_DELAY_MS, `after-contradiction:${event.id}`);
      return finishEvent(event.id, "REJECTED", { error: "Failure callback contradicted by the provider (success)" });
    }
    outcome = q.outcome;
    resultCode = q.resultCode ?? resultCode;
    resultDesc = q.resultDesc || resultDesc;
  }

  if (outcome !== "SUCCESS") {
    await setAttemptOutcome(attempt.id, outcome === "PENDING" ? "UNKNOWN" : outcome, { resultCode, resultDesc, detail: stkMessage(resultCode ?? "", resultDesc) });
    return finishEvent(event.id, "PROCESSED");
  }
  const details: StkSuccessDetails = { amount: p.amount!, receipt: p.receipt!, transactionDate: p.transactionDate ? new Date(p.transactionDate) : null, phone: null };
  const environment = ((attempt.metadata ?? {}) as { environment?: "sandbox" | "production" | "mock" }).environment ?? "mock";
  const paymentId = await confirmAttempt(attempt.id, details, event.id);
  await finishEvent(event.id, "PROCESSED", { paymentId });
  if (attempt.provider === "mpesa_daraja") await recordVerifiedPayment(attempt.organizationId, environment);
}

/** Record the money exactly once and apply it. Returns the payment id. */
async function confirmAttempt(attemptId: string, details: StkSuccessDetails, eventId: string): Promise<string> {
  const run = () =>
    db.$transaction(async (tx) => {
      await tx.$queryRaw`SELECT "id" FROM "PaymentAttempt" WHERE "id" = ${attemptId}::uuid FOR UPDATE`;
      const attempt = await tx.paymentAttempt.findUniqueOrThrow({ where: { id: attemptId } });
      if (attempt.status === "CONFIRMED" && attempt.paymentId) return { paymentId: attempt.paymentId, allocations: [] as AllocationResult[], created: false, attempt };
      const ctx = systemContext(attempt.organizationId, "webhook:mpesa", eventId);
      const existing = await findLivePaymentByReference(tx, attempt.organizationId, details.receipt);
      let paymentId: string;
      let allocations: AllocationResult[] = [];
      let created = false;
      if (existing) {
        paymentId = existing.id; // already recorded (C2B report or manual entry): link, never duplicate
      } else {
        const subscriber = attempt.subscriberId ? await tx.subscriber.findUnique({ where: { id: attempt.subscriberId }, select: { id: true, branchId: true } }) : null;
        const payment = await createConfirmedPaymentTx(tx, ctx, {
          subscriberId: subscriber?.id ?? null,
          branchId: subscriber?.branchId ?? null,
          method: "MPESA",
          provider: attempt.provider,
          providerTransactionId: details.receipt,
          amount: attempt.amount.toString(),
          currency: attempt.currency,
          receivedAt: details.transactionDate && details.transactionDate.getTime() <= Date.now() + 5 * 60_000 ? details.transactionDate : new Date(),
          payerPhone: attempt.phone,
          accountReference: attempt.accountReference,
          notes: attempt.provider === "mock" ? "Simulated M-Pesa payment (mock adapter): no money moved." : "M-Pesa STK Push",
          metadata: { attemptId: attempt.id, channel: attempt.channel, simulated: attempt.provider === "mock" },
        });
        paymentId = payment.id;
        created = true;
        if (payment.subscriberId) {
          if (attempt.invoiceId) {
            const invoice = await tx.invoice.findUnique({ where: { id: attempt.invoiceId }, select: { id: true, subscriberId: true, status: true, balanceDue: true, currency: true } });
            if (invoice && invoice.subscriberId === payment.subscriberId && invoice.currency === payment.currency && (invoice.status === "OPEN" || invoice.status === "PARTIALLY_PAID")) {
              const amount = D.min(new D(payment.amount.toString()), new D(invoice.balanceDue.toString()));
              if (amount.gt(0)) allocations.push(await allocateTx(tx, ctx, payment.id, invoice.id, amount));
            }
          }
          allocations = [...allocations, ...(await autoAllocateForSubscriberTx(tx, ctx, payment.subscriberId, payment.id))];
          await notifyPaymentReceivedTx(tx, attempt.organizationId, payment.id);
        }
      }
      const updated = await tx.paymentAttempt.update({
        where: { id: attemptId },
        data: { status: "CONFIRMED", paymentId, providerReceipt: details.receipt, resultCode: "0", completedAt: new Date(), detail: existing ? `Payment received (already recorded as ${existing.receiptNumber}).` : "Payment received." },
      });
      return { paymentId, allocations, created, attempt: updated };
    });
  let result;
  try {
    result = await run();
  } catch (err) {
    // Unique receipt race (e.g. a C2B report recorded the same receipt concurrently): retry links the existing payment.
    if ((err as { code?: string }).code === "P2002") result = await run();
    else throw err;
  }
  if (result.allocations.some((a) => a.subscription === "renewed")) await dispatchNetworkOperations(result.attempt.organizationId);
  if (result.created) {
    await audit(systemContext(result.attempt.organizationId, "webhook:mpesa", eventId), {
      action: "payment.mpesa.confirmed",
      entityType: "payment",
      entityId: result.paymentId,
      metadata: { attemptId, receipt: details.receipt, amount: result.attempt.amount.toString(), simulated: result.attempt.provider === "mock" },
    });
  }
  return result.paymentId;
}

