export const simulateInput = z.object({ outcome: z.enum(["success", "cancelled", "insufficient_funds", "timeout"]) });
const SIMULATED_CODE: Record<z.infer<typeof simulateInput>["outcome"], string> = { success: "0", cancelled: "1032", insufficient_funds: "1", timeout: "1037" };

/**
 * Development only (mock adapter, never in production): play the customer's response through the real callback
 * pipeline. The resulting payment is labelled simulated and its receipt starts with "SIM".
 */
export async function simulateMockResponse(ctx: StaffContext, id: string, raw: z.input<typeof simulateInput>) {
  requirePermission(ctx, "payments.initiate");
  if (process.env.APP_ENV === "production") throw new AppError("FORBIDDEN", "Simulation is never available in production.");
  const { outcome } = simulateInput.parse(raw);
  const a = await visibleAttempt(ctx, id);
  if (a.provider !== "mock") throw new AppError("INVALID_STATE", "Only requests made with the mock payment adapter can be simulated.");
  if (!a.checkoutRequestId || a.status !== "SUBMITTED") throw new AppError("INVALID_STATE", "This request is no longer waiting for the customer.");
  const resultCode = SIMULATED_CODE[outcome];
  const attempt = await db.paymentAttempt.update({ where: { id: a.id }, data: { metadata: { ...((a.metadata ?? {}) as object), mockResultCode: resultCode } } });
  const now = new Date();
  const ts = new Date(now.getTime() + 3 * 3_600_000).toISOString().replace(/[-:T]/g, "").slice(0, 14); // EAT wall time
  const body = {
    Body: {
      stkCallback: {
        MerchantRequestID: attempt.merchantRequestId,
        CheckoutRequestID: attempt.checkoutRequestId,
        ResultCode: Number(resultCode),
        ResultDesc: resultCode === "0" ? "The service request is processed successfully." : "Simulated failure",
        ...(resultCode === "0"
          ? {
              CallbackMetadata: {
                Item: [
                  { Name: "Amount", Value: Number(attempt.amount) },
                  { Name: "MpesaReceiptNumber", Value: `SIM${randomBytes(4).toString("hex").toUpperCase().slice(0, 7)}` },
                  { Name: "TransactionDate", Value: Number(ts) },
                  { Name: "PhoneNumber", Value: Number(attempt.phone) },
                ],
              },
            }
          : {}),
      },
    },
  };
  await ingestStkCallback(attempt, JSON.stringify(body), { ipAddress: null, correlationId: ctx.correlationId });
  await audit(ctx, { action: "payment.mpesa.simulate", entityType: "payment_attempt", entityId: a.id, metadata: { outcome } });
  return getAttempt(ctx, a.id);
}

