export const attemptListQuery = z.object({
  status: z.enum(["PENDING", "SUBMITTED", "CONFIRMED", "FAILED", "CANCELLED", "EXPIRED", "UNKNOWN", "OPEN", "ALL"]).default("ALL"),
  subscriberId: z.uuid().optional(),
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(25),
});

async function visibleAttempt(ctx: StaffContext, id: string) {
  const a = await db.paymentAttempt.findFirst({ where: { id, organizationId: ctx.organizationId } });
  if (!a) throw notFound("payment request");
  if (ctx.branchIds && a.subscriberId) {
    const s = await db.subscriber.findFirst({ where: { id: a.subscriberId, ...tenantWhere(ctx) }, select: { id: true } });
    if (!s) throw notFound("payment request");
  }
  return a;
}

export async function listAttempts(ctx: StaffContext, query: z.infer<typeof attemptListQuery>) {
  requirePermission(ctx, "payments.read");
  const where: Prisma.PaymentAttemptWhereInput = {
    organizationId: ctx.organizationId,
    ...(ctx.branchIds ? { subscriberId: { in: (await db.subscriber.findMany({ where: tenantWhere(ctx), select: { id: true } })).map((s) => s.id) } } : {}),
    ...(query.subscriberId ? { subscriberId: query.subscriberId } : {}),
    ...(query.status === "OPEN" ? { status: { in: OPEN_ATTEMPT } } : query.status !== "ALL" ? { status: query.status } : {}),
  };
  const [rows, total, counts] = await Promise.all([
    db.paymentAttempt.findMany({ where, orderBy: { createdAt: "desc" }, skip: (query.page - 1) * query.pageSize, take: query.pageSize }),
    db.paymentAttempt.count({ where }),
    db.paymentAttempt.groupBy({ by: ["status"], where: { organizationId: ctx.organizationId }, _count: { _all: true } }),
  ]);
  const subs = await db.subscriber.findMany({ where: { id: { in: rows.map((r) => r.subscriberId).filter((x): x is string => Boolean(x)) } }, select: { id: true, displayName: true, accountNumber: true } });
  return {
    rows: rows.map((a) => ({ ...publicAttempt(a), subscriber: subs.find((s) => s.id === a.subscriberId) ?? null })),
    total,
    counts: Object.fromEntries(counts.map((c) => [c.status, c._count._all])) as Partial<Record<PaymentAttemptStatus, number>>,
  };
}

export async function getAttempt(ctx: StaffContext, id: string) {
  requirePermission(ctx, "payments.read");
  const a = await visibleAttempt(ctx, id);
  const [events, subscriber, payment, invoice] = await Promise.all([
    db.webhookEvent.findMany({ where: { attemptId: a.id }, orderBy: { receivedAt: "asc" }, select: { id: true, kind: true, status: true, error: true, duplicateCount: true, conflictingDuplicate: true, receivedAt: true, processedAt: true, payload: true } }),
    a.subscriberId ? db.subscriber.findUnique({ where: { id: a.subscriberId }, select: { id: true, displayName: true, accountNumber: true } }) : null,
    a.paymentId ? db.payment.findUnique({ where: { id: a.paymentId }, select: { id: true, receiptNumber: true, amount: true, status: true } }) : null,
    a.invoiceId ? db.invoice.findUnique({ where: { id: a.invoiceId }, select: { id: true, invoiceNumber: true } }) : null,
  ]);
  return { ...publicAttempt(a), queryCount: a.queryCount, lastQueriedAt: a.lastQueriedAt, events, subscriber, payment, invoice, canSimulate: a.provider === "mock" && process.env.APP_ENV !== "production" };
}

