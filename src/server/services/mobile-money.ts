/** Worker: ask the provider for the final state when no callback arrived. */
export async function runStatusQuery(attemptId: string, opts: { final: boolean }) {
  const attempt = await db.paymentAttempt.findUnique({ where: { id: attemptId } });
  if (!attempt || attempt.status !== "SUBMITTED" || !attempt.checkoutRequestId) return { skipped: true };
  // A stored success callback waiting for verification takes precedence.
  const pending = await db.webhookEvent.findFirst({ where: { attemptId, kind: "stk_callback", status: { in: ["RECEIVED", "FAILED"] } } });
  if (pending) {
    await processStkEvent(pending.id, opts);
    return { verifiedCallback: true };
  }
  const gw = await resolveGateway(attempt.organizationId);
  const mockResultCode = ((attempt.metadata ?? {}) as { mockResultCode?: string }).mockResultCode ?? null;
  const q = await gw.gateway.queryPayment(attempt.checkoutRequestId, { mockResultCode, createdAt: attempt.createdAt });
  await db.paymentAttempt.update({ where: { id: attempt.id }, data: { lastQueriedAt: new Date(), queryCount: { increment: 1 } } });
  if (q.outcome === "PENDING") {
    if (opts.final) {
      await setAttemptOutcome(attempt.id, "UNKNOWN", { detail: "M-Pesa had not finished the request after several checks. If the customer paid, the payment is recorded when M-Pesa reports it." });
      return { outcome: "UNKNOWN" };
    }
    throw new RetryableError("Still waiting for the customer", "STK_PENDING");
  }
  if (q.outcome === "SUCCESS") {
    // Success without the callback means no receipt number yet: do not record money from a status query alone.
    if (opts.final) {
      await setAttemptOutcome(attempt.id, "UNKNOWN", { resultCode: q.resultCode, detail: "M-Pesa reports this payment succeeded, but the confirmation with the receipt number has not arrived. Match it from the M-Pesa statement (Reconciliation)." });
      return { outcome: "UNKNOWN" };
    }
    await db.paymentAttempt.update({ where: { id: attempt.id }, data: { detail: "M-Pesa reports success; waiting for the confirmation with the receipt number." } });
    throw new RetryableError("Waiting for the confirmation callback", "AWAITING_CALLBACK");
  }
  await setAttemptOutcome(attempt.id, q.outcome, { resultCode: q.resultCode, resultDesc: q.resultDesc, detail: stkMessage(q.resultCode ?? "", q.resultDesc) });
  return { outcome: q.outcome };
}

// ───────── C2B (payments made directly to the paybill/till) ─────────

async function matchPayer(tx: Tx, organizationId: string, billRef: string, msisdn: string | null) {
  const ref = normaliseBillRef(billRef);
  if (ref) {
    const sub = await tx.subscriber.findFirst({ where: { organizationId, accountNumber: ref }, select: { id: true, branchId: true } });
    if (sub) return { subscriber: sub, invoiceId: null as string | null, matchedBy: "account" };
    const inv = await tx.invoice.findFirst({ where: { organizationId, invoiceNumber: ref }, select: { id: true, subscriberId: true } });
    if (inv) {
      const s = await tx.subscriber.findUnique({ where: { id: inv.subscriberId }, select: { id: true, branchId: true } });
      if (s) return { subscriber: s, invoiceId: inv.id, matchedBy: "invoice" };
    }
  }
  if (msisdn && /^254[17]\d{8}$/.test(msisdn)) {
    const subs = await tx.subscriber.findMany({ where: { organizationId, phone: msisdn, status: { not: "ARCHIVED" } }, select: { id: true, branchId: true }, take: 2 });
    if (subs.length === 1) return { subscriber: subs[0]!, invoiceId: null, matchedBy: "phone" };
  }
  return null;
}

/** POST /webhooks/mobile-money/c2b/:token/confirmation */
export async function handleC2bConfirmationRequest(token: string, rawBody: string, meta: WebhookMeta): Promise<WebhookResponse> {
  if (!/^[A-Za-z0-9_-]{20,100}$/.test(token)) return { status: 404, body: { error: "Not found" } };
  if (!callbackSourceAllowed(meta.ipAddress)) return { status: 403, body: { error: "Forbidden" } };
  await consumeRateLimit(RATE_LIMITS.webhook, `c2b:${meta.ipAddress ?? "unknown"}`);
  if (Buffer.byteLength(rawBody) > MAX_WEBHOOK_BYTES) return { status: 413, body: { error: "Too large" } };
  const cfg = await c2bConfigForToken(token);
  if (!cfg) return { status: 404, body: { error: "Not found" } };
  const fingerprint = sha256(rawBody);
  const parsed = c2bConfirmationSchema.safeParse(parseJson(rawBody));
  if (!parsed.success) return { status: 400, body: { ResultCode: 1, ResultDesc: "Rejected" } };
  const c = parsed.data;
  const receipt = c.TransID.toUpperCase();
  const amount = new D(String(c.TransAmount));
  const msisdn = c.MSISDN === undefined ? null : String(c.MSISDN);
  const payload = {
    transId: receipt,
    transTime: String(c.TransTime),
    amount: String(c.TransAmount),
    shortcode: String(c.BusinessShortCode),
    billRef: c.BillRefNumber.slice(0, 40),
    payerName: [c.FirstName, c.MiddleName, c.LastName].filter(Boolean).join(" ").slice(0, 120),
    msisdn: msisdn && /^\d{12}$/.test(msisdn) ? maskMsisdn(msisdn) : msisdn ? "masked" : null,
  };
  const { event, duplicate } = await storeEvent({ organizationId: cfg.organizationId, provider: "mpesa_daraja", kind: "c2b_confirmation", eventKey: receipt, fingerprint, payload, sourceIp: meta.ipAddress });
  if (duplicate && (event.status === "PROCESSED" || event.status === "REJECTED")) return { status: 200, body: ACK };
  const expected = [cfg.shortcode, cfg.tillNumber].filter(Boolean);
  if (!expected.includes(payload.shortcode)) {
    logger.warn({ eventId: event.id }, "c2b confirmation for a different shortcode");
    await finishEvent(event.id, "REJECTED", { error: "Shortcode does not match this organization" });
    return { status: 200, body: ACK };
  }
  if (!amount.isFinite() || amount.lte(0) || amount.gt(MPESA_MAX_AMOUNT * 4)) {
    await finishEvent(event.id, "REJECTED", { error: "Invalid amount" });
    return { status: 200, body: ACK };
  }
  try {
    const result = await db.$transaction(async (tx) => {
      const ctx = systemContext(cfg.organizationId, "webhook:mpesa-c2b", event.id);
      const existing = await findLivePaymentByReference(tx, cfg.organizationId, receipt);
      if (existing) return { paymentId: existing.id, allocations: [] as AllocationResult[], matchedBy: "existing", created: false };
      const org = await tx.organization.findUniqueOrThrow({ where: { id: cfg.organizationId }, select: { currency: true } });
      const match = await matchPayer(tx, cfg.organizationId, c.BillRefNumber, msisdn);
      const payment = await createConfirmedPaymentTx(tx, ctx, {
        subscriberId: match?.subscriber.id ?? null,
        branchId: match?.subscriber.branchId ?? null,
        method: "MPESA",
        provider: "mpesa_daraja",
        providerTransactionId: receipt,
        amount: amount.toFixed(2),
        currency: org.currency,
        receivedAt: parseDarajaTimestamp(c.TransTime) ?? new Date(),
        payerName: payload.payerName || null,
        payerPhone: msisdn && /^254[17]\d{8}$/.test(msisdn) ? msisdn : null,
        accountReference: c.BillRefNumber.slice(0, 100) || null,
        notes: match ? `M-Pesa paybill payment (matched by ${match.matchedBy})` : "M-Pesa paybill payment: account reference not recognised, awaiting reconciliation",
        metadata: { channel: "c2b", matchedBy: match?.matchedBy ?? null },
      });
      let allocations: AllocationResult[] = [];
      if (match) {
        if (match.invoiceId) {
          const invoice = await tx.invoice.findUnique({ where: { id: match.invoiceId }, select: { id: true, status: true, balanceDue: true, currency: true } });
          if (invoice && invoice.currency === payment.currency && (invoice.status === "OPEN" || invoice.status === "PARTIALLY_PAID")) {
            const a = D.min(new D(payment.amount.toString()), new D(invoice.balanceDue.toString()));
            if (a.gt(0)) allocations.push(await allocateTx(tx, ctx, payment.id, invoice.id, a));
          }
        }
        allocations = [...allocations, ...(await autoAllocateForSubscriberTx(tx, ctx, match.subscriber.id, payment.id))];
        await notifyPaymentReceivedTx(tx, cfg.organizationId, payment.id);
      }
      return { paymentId: payment.id, allocations, matchedBy: match?.matchedBy ?? null, created: true };
    });
    await finishEvent(event.id, "PROCESSED", { paymentId: result.paymentId });
    if (result.allocations.some((a) => a.subscription === "renewed")) await dispatchNetworkOperations(cfg.organizationId);
    if (result.created) {
      await audit(systemContext(cfg.organizationId, "webhook:mpesa-c2b", event.id), { action: "payment.mpesa.c2b", entityType: "payment", entityId: result.paymentId, metadata: { receipt, amount: amount.toFixed(2), matchedBy: result.matchedBy } });
    }
  } catch (err) {
    if ((err as { code?: string }).code === "P2002") {
      // The same receipt was recorded concurrently by another path: acknowledged, nothing duplicated.
      await finishEvent(event.id, "PROCESSED", { error: "Receipt already recorded" });
    } else {
      logger.error({ eventId: event.id, err: err instanceof Error ? err.name : "unknown" }, "c2b confirmation processing failed");
      await finishEvent(event.id, "FAILED", { error: err instanceof Error ? err.message : "Processing failed" });
      return { status: 500, body: { ResultCode: 1, ResultDesc: "Temporary error" } };
    }
  }
  return { status: 200, body: ACK };
}

/** POST /webhooks/mobile-money/c2b/:token/validation (only called when Safaricom enabled external validation). */
export async function handleC2bValidationRequest(token: string, rawBody: string, meta: WebhookMeta): Promise<WebhookResponse> {
  if (!/^[A-Za-z0-9_-]{20,100}$/.test(token)) return { status: 404, body: { error: "Not found" } };
  if (!callbackSourceAllowed(meta.ipAddress)) return { status: 403, body: { error: "Forbidden" } };
  const cfg = await c2bConfigForToken(token);
  if (!cfg) return { status: 404, body: { error: "Not found" } };
  const parsed = c2bConfirmationSchema.safeParse(parseJson(rawBody));
  if (!parsed.success) return { status: 200, body: { ResultCode: "C2B00016", ResultDesc: "Rejected" } };
  if (cfg.rejectUnknownAccounts) {
    const match = await matchPayer(db, cfg.organizationId, parsed.data.BillRefNumber, null);
    if (!match) return { status: 200, body: { ResultCode: "C2B00012", ResultDesc: "Rejected" } }; // invalid account number
  }
  return { status: 200, body: { ResultCode: "0", ResultDesc: "Accepted" } };
}

