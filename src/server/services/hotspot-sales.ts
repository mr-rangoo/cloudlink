interface Meta {
  ipAddress: string | null;
  userAgent: string | null;
  correlationId: string;
}

async function portalOrg(slug: string) {
  const org = await db.organization.findUnique({ where: { slug }, select: { id: true, slug: true, name: true, currency: true, timezone: true, status: true } });
  if (!org || org.status !== "ACTIVE") throw new AppError("NOT_FOUND", "Unknown hotspot.");
  return org;
}

function portalContext(organizationId: string, meta: Meta): SystemContext {
  return { ...systemContext(organizationId, "hotspot:portal", meta.correlationId), ipAddress: meta.ipAddress, userAgent: meta.userAgent };
}

/** What the customer pays for one period: price plus tax, rounded exactly as the invoice line will be. */
export function grossPrice(pkg: Pick<Package, "price" | "taxRate">): DecimalValue {
  return computeLine({ description: "plan", quantity: "1", unitPrice: pkg.price.toString(), taxRate: pkg.taxRate.toString() }).lineTotal;
}

/** Token the captive portal holds for one purchase: derived from its request id, so a retried request gets the same one. */
function portalToken(organizationId: string, requestId: string): string {
  const key = process.env.APP_ENCRYPTION_KEY;
  if (!key) throw new Error("APP_ENCRYPTION_KEY is not configured");
  return Buffer.from(hmacSha256(key, `hotspot-purchase:${organizationId}:${requestId}`), "hex").toString("base64url");
}

/** A hotspot router named by the login page, or the organization's only hotspot router. */
async function purchaseRouter(organizationId: string, routerId: string | null | undefined) {
  if (routerId) {
    const r = await db.router.findFirst({ where: { id: routerId, organizationId, archivedAt: null, hotspotEnabled: true }, select: { id: true, name: true, hotspotDnsName: true } });
    if (r) return r;
  }
  const fallback = await defaultHotspotRouterId(db, organizationId);
  return fallback ? db.router.findUnique({ where: { id: fallback }, select: { id: true, name: true, hotspotDnsName: true } }) : null;
}

