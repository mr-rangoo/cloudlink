/**
 * "Already paid?": a customer who bought a plan proves it with the M-Pesa confirmation code and the paying phone,
 * and gets the login details again (new device, cleared browser). If they are now at another of the organization's
 * hotspots, their login is moved there.
 */
export async function reconnectHotspot(slug: string, raw: z.input<typeof reconnectInput>, meta: Meta) {
  const input = reconnectInput.parse(raw);
  const ipKey = meta.ipAddress ?? "unknown";
  await consumeRateLimit(RECONNECT_IP_LIMIT, ipKey);
  const org = await portalOrg(slug);
  const phone = toMsisdn(input.phone);
  const notMatched = () => new AppError("NOT_FOUND", "We could not find an active plan for that M-Pesa code and phone number.");
  if (!phone) throw notMatched();
  const payment = await db.payment.findFirst({ where: { organizationId: org.id, providerTransactionId: input.receipt, status: "CONFIRMED", payerPhone: phone }, select: { id: true, subscriberId: true } });
  const attempt = payment ? await db.paymentAttempt.findFirst({ where: { paymentId: payment.id, purpose: "hotspot_purchase" }, select: { subscriptionId: true } }) : null;
  let sub = attempt?.subscriptionId ? await db.subscription.findUnique({ where: { id: attempt.subscriptionId } }) : null;
  if (!sub || sub.status !== "ACTIVE" || !sub.currentPeriodEnd || sub.currentPeriodEnd <= new Date() || !sub.networkUsername || !sub.networkPasswordEnc) throw notMatched();
  await refundRateLimit(RECONNECT_IP_LIMIT, ipKey);

  const router = input.routerId ? await purchaseRouter(org.id, input.routerId) : null;
  const moved = Boolean(router && sub.networkRouterId && router.id !== sub.networkRouterId);
  if (router && moved) {
    const pkg = await db.package.findUniqueOrThrow({ where: { id: sub.packageId } });
    await assertPlanAllowedOnRouter(db, pkg.id, router.id);
    const ctx = portalContext(org.id, meta);
    const current = sub;
    sub = await db.$transaction(async (tx) => {
      await lockRow(tx, "Subscription", current.id);
      const kind = pkg.kind === "DEVICE" ? "device" : "hotspot";
      for (const [type, routerId] of [
        [kind === "device" ? "device.binding.disable" : "hotspot.access.disable", current.networkRouterId!],
        [kind === "device" ? "device.binding.enable" : "hotspot.access.enable", router.id],
      ] as const) {
        await requestNetworkOperationTx(tx, ctx, { type, routerId, subscriptionId: current.id, subscriberId: current.subscriberId, params: { username: current.networkUsername!, reason: "Customer reconnected at another hotspot" }, idempotencyKey: `hotspot-reconnect:${current.id}:${type}:${routerId}:${meta.correlationId}` });
      }
      return tx.subscription.update({ where: { id: current.id }, data: { networkRouterId: router.id, networkStatus: "PENDING", networkUpdatedAt: new Date() } });
    });
    await dispatchNetworkOperations(org.id, { subscriptionId: sub.id });
  }
  await audit(portalContext(org.id, meta), { action: "hotspot.reconnect", entityType: "subscription", entityId: sub.id, metadata: { receipt: input.receipt, moved } });
  return { grant: grantView(sub, sub.packageName) };
}

// ───────── Router login address ─────────

const PRIVATE_V4 = /^(10\.\d{1,3}\.\d{1,3}\.\d{1,3}|192\.168\.\d{1,3}\.\d{1,3}|172\.(1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3})$/;

/**
 * The router login URL the portal may post login details to: http(s), path /login, on a private IPv4 address or the
 * router's configured hotspot name. Anything else (an external site in a crafted link) is refused.
 */
export function safeRouterLoginUrl(raw: string | null | undefined, routerHost: string | null): string | null {
  if (!raw) return null;
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    return null;
  }
  if ((url.protocol !== "http:" && url.protocol !== "https:") || url.pathname !== "/login" || url.username || url.password) return null;
  const host = url.hostname.toLowerCase();
  if (!PRIVATE_V4.test(host) && !(routerHost && host === routerHost.toLowerCase())) return null;
  return `${url.protocol}//${url.host}/login`;
}

