/**
 * The hotspot login page Cloudlink asks routers to serve (hotspot/login.html): it forwards the MikroTik variables to
 * this organization's captive portal. It contains no secrets; the router id only tells the portal where the device is.
 */
export async function routerLoginPage(routerId: string): Promise<string | null> {
  const router = await db.router.findFirst({ where: { id: routerId, archivedAt: null, hotspotEnabled: true }, select: { id: true, organizationId: true } });
  if (!router) return null;
  const org = await db.organization.findUnique({ where: { id: router.organizationId }, select: { slug: true, name: true } });
  if (!org) return null;
  const base = (process.env.APP_URL ?? "").replace(/\/$/, "");
  const target = `${base}/hotspot/${org.slug}?router=${router.id}&mac=$(mac-esc)&ip=$(ip-esc)&link-login-only=$(link-login-only-esc)&dst=$(link-orig-esc)`;
  const name = org.name.replace(/[<>&"]/g, "");
  return [
    "<!doctype html>",
    '<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">',
    `<title>${name} WiFi</title>`,
    `<meta http-equiv="refresh" content="0; url=${target}">`,
    "</head><body style=\"font-family:system-ui,sans-serif;text-align:center;padding:3rem 1rem\">",
    `<p>Opening ${name} WiFi…</p><p><a href="${target}">Continue</a></p>`,
    "</body></html>",
    "",
  ].join("\n");
}
