/**
 * Self-service hotspot sales on the captive portal.
 *
 * A customer picks a live hotspot plan and enters an M-Pesa number. Cloudlink finds or creates a hotspot subscriber
 * for that number and sends an STK Push. Nothing is granted on the browser's word: only a validated, verified
 * callback (services/mobile-money.ts) calls applyHotspotPurchaseTx, which — in the same transaction that records the
 * money — activates or renews the customer's hotspot subscription, issues the period invoice and pays it with exactly
 * this payment, and queues the router change. The captive portal follows the purchase with a token only it holds and
 * receives the login details once the payment is confirmed, then logs the device in on the router.
 */

const MAC_RE = /^([0-9A-Fa-f]{2}[:-]){5}[0-9A-Fa-f]{2}$/;
const macField = z
  .string()
  .trim()
  .regex(MAC_RE, "Enter a MAC address such as AA:BB:CC:DD:EE:FF")
  .transform((v) => v.toUpperCase().replaceAll("-", ":"));
const optionalMac = z.union([macField, z.literal("").transform(() => null), z.null()]).optional();
const optionalIp = z.union([z.ipv4(), z.literal("").transform(() => null), z.null()]).optional();

export const purchaseInput = z.object({
  packageId: z.uuid(),
  phone: z.string().trim().min(9).max(20),
  /** The buying device (from the router's login page). */
  mac: optionalMac,
  ip: optionalIp,
  routerId: z.uuid().optional().nullable(),
  /** TV / device plans: the device that gets access (it cannot open this page itself). */
  deviceMac: optionalMac,
  /** Generated by the page; the same request id always maps to the same purchase. */
  requestId: z.uuid(),
});

export const purchaseStatusInput = z.object({ attemptId: z.uuid(), token: z.string().min(20).max(128) });
export const purchaseSimulateInput = purchaseStatusInput.extend({ outcome: simulateInput.shape.outcome });
export const accessStatusInput = z.object({ subscriptionId: z.uuid(), username: z.string().min(3).max(64), password: z.string().min(4).max(64) });
export const reconnectInput = z.object({
  phone: z.string().trim().min(9).max(20),
  receipt: z
    .string()
    .trim()
    .toUpperCase()
    .regex(/^[A-Z0-9]{8,14}$/, "Enter the M-Pesa confirmation code, e.g. UJT17BQ5BX"),
  mac: optionalMac,
  routerId: z.uuid().optional().nullable(),
});

const PURCHASE_IP_LIMIT = { name: "hotspot:purchase:ip", limit: 30, windowSeconds: 10 * 60 };
const STATUS_IP_LIMIT = { name: "hotspot:status:ip", limit: 120, windowSeconds: 10 * 60 };
const RECONNECT_IP_LIMIT = { name: "hotspot:reconnect:ip", limit: 10, windowSeconds: 10 * 60 };
