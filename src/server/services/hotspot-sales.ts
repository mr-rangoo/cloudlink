/** Start buying a plan: free trials are granted directly; paid plans send an M-Pesa prompt. */
export async function startHotspotPurchase(slug: string, raw: z.input<typeof purchaseInput>, meta: Meta) {
  const input = purchaseInput.parse(raw);
  await consumeRateLimit(PURCHASE_IP_LIMIT, meta.ipAddress ?? "unknown");
  const org = await portalOrg(slug);
  await consumeRateLimit({ name: "hotspot:purchase:org", limit: 600, windowSeconds: 60 }, org.id);
  const phone = toMsisdn(input.phone);
  if (!phone) throw new AppError("VALIDATION_ERROR", "Enter a Safaricom number such as 0712 345 678.", { fields: [{ path: "phone", message: "Not an M-Pesa number" }] });
  const pkg = await db.package.findFirst({ where: { id: input.packageId, organizationId: org.id, status: "ACTIVE", listed: true, serviceType: "HOTSPOT" } });
  if (!pkg) throw new AppError("NOT_FOUND", "This plan is no longer available. Refresh the page.");
  const router = await purchaseRouter(org.id, input.routerId);
  await assertPlanAllowedOnRouter(db, pkg.id, router?.id ?? null);
  assertPlanOpen(pkg, new Date(), org.timezone);
  if (!router && networkAdapterName() !== "mock") throw new AppError("INVALID_STATE", "Online purchase is not set up on this hotspot yet. Please ask the attendant.");
  const deviceMac = pkg.kind === "DEVICE" ? (input.deviceMac ?? null) : null;
  if (pkg.kind === "DEVICE" && !deviceMac) throw new AppError("VALIDATION_ERROR", "Enter the MAC address of the TV or device.", { fields: [{ path: "deviceMac", message: "Required for device plans" }] });
  const ctx = portalContext(org.id, meta);
  const gross = grossPrice(pkg);

  if (gross.isZero()) return claimTrial(ctx, org, pkg, phone, input, router?.id ?? null);

  const amount = gross.toNumber();
  const problem = stkAmountProblem(amount);
  if (problem) throw new AppError("INVALID_STATE", amount > MPESA_MAX_AMOUNT ? problem : "This plan's price cannot be paid with M-Pesa (it must be whole shillings). Please ask the attendant.");
  const token = portalToken(org.id, input.requestId);
  const key = `hotspot:${input.requestId}`;
  const prior = await db.paymentAttempt.findUnique({ where: { organizationId_idempotencyKey: { organizationId: org.id, idempotencyKey: key } } });
  if (prior) return purchaseView(prior, token, pkg.name);

  const subscriber = await db.$transaction((tx) => findOrCreateHotspotSubscriberTx(tx, ctx, phone));
  const suspended = await db.subscription.count({ where: { subscriberId: subscriber.id, serviceType: "HOTSPOT", status: "SUSPENDED" } });
  if (suspended) throw new AppError("INVALID_STATE", "This account is suspended. Please contact support.");
  await consumeRateLimit(RATE_LIMITS.paymentInitiation, `${org.id}:phone:${phone}`);
  const attempt = await submitPaymentAttempt(ctx, {
    subscriber,
    invoiceId: null,
    phone,
    amount,
    currency: org.currency,
    channel: "hotspot",
    idempotencyKey: key,
    purchase: { packageId: pkg.id, routerId: router?.id ?? null, clientMac: deviceMac ?? input.mac ?? null, clientIp: input.ip ?? meta.ipAddress, portalTokenHash: sha256(token) },
  });
  await audit(ctx, { action: "hotspot.purchase.start", entityType: "payment_attempt", entityId: attempt.id, metadata: { packageId: pkg.id, amount: gross.toFixed(2), phone: maskMsisdn(phone), routerId: router?.id ?? null, status: attempt.status } });
  return purchaseView(attempt, token, pkg.name);
}

function purchaseView(a: PaymentAttempt, token: string, packageName: string) {
  return { attemptId: a.id, token, status: a.status, detail: a.detail, amount: a.amount.toString(), packageName, testMode: a.provider === "mock" };
}

/** Free trial: once per phone number and per device within the plan's cool-down. */
async function claimTrial(ctx: SystemContext, org: { id: string }, pkg: Package, phone: string, input: z.infer<typeof purchaseInput>, routerId: string | null) {
  const cooldownDays = pkg.trialCooldownDays ?? 30;
  const since = new Date(Date.now() - cooldownDays * 86_400_000);
  const mac = input.mac ?? null;
  const key = `hotspot-trial:${input.requestId}`;
  const result = await db.$transaction(async (tx) => {
    // The phone lock (inside findOrCreate) serialises claims, so two quick claims cannot both pass the check.
    const subscriber = await findOrCreateHotspotSubscriberTx(tx, ctx, phone);
    await lockRow(tx, "Subscriber", subscriber.id);
    const used = await tx.subscriptionEvent.findFirst({
      where: {
        organizationId: org.id,
        type: { in: ["activated", "renewed"] },
        createdAt: { gte: since },
        idempotencyKey: { startsWith: "hotspot-trial:", not: key },
        metadata: { path: ["packageId"], equals: pkg.id },
        subscription: { OR: [{ subscriber: { phone } }, ...(mac ? [{ networkMac: mac }] : [])] },
      },
      select: { createdAt: true },
    });
    if (used && cooldownDays > 0) {
      throw new AppError("CONFLICT", `This trial has already been used on this phone or device. It can be taken again after ${new Date(used.createdAt.getTime() + cooldownDays * 86_400_000).toLocaleDateString("en-KE")}.`);
    }
    const grant = await grantPeriodTx(tx, ctx, { subscriber, pkg, routerId, mac, deviceMac: null, idempotencyKey: key, reason: "Free trial from the captive portal", payment: null });
    if (!grant.applied) throw new AppError("INVALID_STATE", "This account is suspended. Please contact support.");
    const event = await tx.subscriptionEvent.findUnique({ where: { subscriptionId_idempotencyKey: { subscriptionId: grant.subscription.id, idempotencyKey: key } } });
    if (event) await tx.subscriptionEvent.update({ where: { id: event.id }, data: { metadata: { ...((event.metadata ?? {}) as object), packageId: pkg.id, phone: maskMsisdn(phone) } } });
    return grant.subscription;
  });
  await dispatchNetworkOperations(org.id, { subscriptionId: result.id });
  await audit(ctx, { action: "hotspot.trial.claim", entityType: "subscription", entityId: result.id, metadata: { packageId: pkg.id, phone: maskMsisdn(phone) } });
  return { trial: true as const, grant: grantView(result, pkg.name) };
}

function grantView(sub: Subscription, packageName: string) {
  return {
    subscriptionId: sub.id,
    username: sub.networkUsername!,
    password: openNetworkPassword(sub.id, sub.networkPasswordEnc!),
    packageName,
    accessEndsAt: sub.currentPeriodEnd,
    ...accessState(sub),
  };
}

function accessState(sub: Pick<Subscription, "networkStatus" | "status" | "currentPeriodEnd">) {
  const ready = sub.status === "ACTIVE" && (sub.networkStatus === "ACTIVE" || sub.networkStatus === "SIMULATED_ACTIVE");
  return { networkStatus: sub.networkStatus, ready, simulated: sub.networkStatus.startsWith("SIMULATED"), failed: sub.networkStatus === "ERROR" };
}

/** The portal follows its purchase; login details are returned only to the token holder, once paid, within 24 hours. */
export async function hotspotPurchaseStatus(slug: string, raw: z.input<typeof purchaseStatusInput>, ipAddress: string | null) {
  const input = purchaseStatusInput.parse(raw);
  const ipKey = ipAddress ?? "unknown";
  await consumeRateLimit(STATUS_IP_LIMIT, ipKey);
  const org = await portalOrg(slug);
  const a = await db.paymentAttempt.findFirst({ where: { id: input.attemptId, organizationId: org.id, purpose: "hotspot_purchase" } });
  if (!a || !a.portalTokenHash || !safeEqual(a.portalTokenHash, sha256(input.token))) throw notFound("purchase");
  await refundRateLimit(STATUS_IP_LIMIT, ipKey);
  const pkg = a.packageId ? await db.package.findUnique({ where: { id: a.packageId }, select: { name: true } }) : null;
  const sub = a.status === "CONFIRMED" && a.subscriptionId && Date.now() - a.createdAt.getTime() < CREDENTIALS_WINDOW_MS ? await db.subscription.findUnique({ where: { id: a.subscriptionId } }) : null;
  return {
    status: a.status,
    detail: a.detail,
    receipt: a.status === "CONFIRMED" ? a.providerReceipt : null,
    testMode: a.provider === "mock",
    grant: sub?.networkUsername && sub.networkPasswordEnc ? grantView(sub, pkg?.name ?? sub.packageName) : null,
  };
}

