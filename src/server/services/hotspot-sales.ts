/** One hotspot customer per phone number (serialised per organization + phone so concurrent purchases agree). */
async function findOrCreateHotspotSubscriberTx(tx: Tx, ctx: ActorContext, phone: string) {
  await tx.$queryRaw`SELECT 1 AS locked FROM pg_advisory_xact_lock(hashtext(${`hotspot-subscriber:${ctx.organizationId}:${phone}`}))`;
  const existing = await tx.subscriber.findMany({ where: { organizationId: ctx.organizationId, phone, status: { not: "ARCHIVED" } }, select: { id: true, accountNumber: true, source: true, status: true }, orderBy: { createdAt: "asc" }, take: 5 });
  const pick = existing.find((s) => s.source === "hotspot") ?? existing[0];
  if (pick) return pick;
  const accountNumber = formatAccountNumber(await nextCounter(tx, ctx.organizationId, "subscriber.account"));
  const local = `0${phone.slice(3)}`;
  const created = await tx.subscriber.create({
    data: { organizationId: ctx.organizationId, accountNumber, type: "INDIVIDUAL", displayName: `${local.slice(0, 4)} ${local.slice(4, 7)} ${local.slice(7)}`, phone, source: "hotspot" },
    select: { id: true, accountNumber: true, source: true, status: true },
  });
  await tx.subscriberActivity.create({ data: { organizationId: ctx.organizationId, subscriberId: created.id, type: "created", message: `Hotspot customer ${accountNumber} created from the captive portal` } });
  return created;
}

/** The subscription a purchase extends: the customer's hotspot login, or the subscription of that one device. */
async function slotSubscription(tx: Tx, subscriberId: string, pkg: Pick<Package, "kind">, deviceMac: string | null) {
  return tx.subscription.findFirst({
    where: {
      subscriberId,
      serviceType: "HOTSPOT",
      status: { not: "CANCELLED" },
      package: pkg.kind === "DEVICE" ? { kind: "DEVICE" } : { kind: { not: "DEVICE" } },
      ...(pkg.kind === "DEVICE" ? { networkMac: deviceMac } : {}),
    },
    orderBy: { createdAt: "desc" },
  });
}

async function uniqueUsername(tx: Tx, organizationId: string, base: string): Promise<string> {
  for (let i = 1; i < 50; i++) {
    const candidate = i === 1 ? base : `${base}-${i}`;
    if (!(await tx.subscription.findFirst({ where: { organizationId, networkUsername: candidate }, select: { id: true } }))) return candidate;
  }
  throw new AppError("CONFLICT", "Could not allocate a hotspot username.");
}

interface GrantArgs {
  subscriber: { id: string; accountNumber: string };
  pkg: Package;
  routerId: string | null;
  mac: string | null;
  deviceMac: string | null;
  idempotencyKey: string;
  reason: string;
  /** Paid purchases: the confirmed payment that pays the period invoice (exactly). */
  payment: Pick<Payment, "id" | "amount"> | null;
}

/**
 * Activate or extend the customer's access for one period of the plan. Runs inside the caller's transaction.
 * - same plan while active: the new period follows the current one;
 * - a different plan while active: the new plan starts now (the remaining time of the old plan is replaced);
 * - expired or new: starts now.
 * Network fields are set before the lifecycle action so the router change is queued in this transaction.
 */
async function grantPeriodTx(tx: Tx, ctx: ActorContext, a: GrantArgs): Promise<{ applied: true; subscription: Subscription } | { applied: false; reason: string }> {
  const kind = a.pkg.kind === "DEVICE" ? "device" : "hotspot";
  let sub = await slotSubscription(tx, a.subscriber.id, a.pkg, a.deviceMac);
  if (sub?.status === "SUSPENDED") return { applied: false, reason: "The account is suspended. Staff must reactivate it before new purchases apply." };
  if (!sub) sub = await createSubscriptionTx(tx, ctx, { subscriberId: a.subscriber.id, packageId: a.pkg.id, activate: false, autoRenew: false, graceDays: 0 });
  await lockRow(tx, "Subscription", sub.id);
  sub = await tx.subscription.findUniqueOrThrow({ where: { id: sub.id } });

  const routerId = a.routerId ?? sub.networkRouterId;
  const username = sub.networkUsername ?? (await uniqueUsername(tx, ctx.organizationId, kind === "device" ? `${a.subscriber.accountNumber.toLowerCase()}-tv` : a.subscriber.accountNumber.toLowerCase()));
  if (sub.networkRouterId && routerId && sub.networkRouterId !== routerId && sub.networkUsername) {
    // Moved to another site: take the login (or device) off the old router.
    await requestNetworkOperationTx(tx, ctx, {
      type: kind === "device" ? "device.binding.disable" : "hotspot.access.disable",
      routerId: sub.networkRouterId,
      subscriptionId: sub.id,
      subscriberId: sub.subscriberId,
      params: { username: sub.networkUsername, reason: "Moved to another router" },
      idempotencyKey: `hotspot-move:${sub.id}:${a.idempotencyKey}`,
    });
  }
  const samePlan = sub.packageId === a.pkg.id;
  sub = await tx.subscription.update({
    where: { id: sub.id },
    data: {
      // A purchase is a new sale at today's price and terms.
      packageId: a.pkg.id,
      packageName: a.pkg.name,
      price: a.pkg.price,
      taxRate: a.pkg.taxRate,
      billingUnit: a.pkg.billingUnit,
      billingCount: a.pkg.billingCount,
      networkRouterId: routerId,
      networkUsername: username,
      networkPasswordEnc: sub.networkPasswordEnc ?? sealNetworkPassword(sub.id, generatePppoePassword(8)),
      networkMac: kind === "device" ? a.deviceMac : (a.mac ?? sub.networkMac),
      ...(routerId ? {} : { networkStatus: "NOT_PROVISIONED" }),
    },
  });
  const action = sub.status === "PENDING" ? "activate" : "renew";
  const updated = await applyActionTx(tx, ctx, sub.id, action, { idempotencyKey: a.idempotencyKey, invoice: false, restart: sub.status === "ACTIVE" && !samePlan, reason: a.reason });
  if (!routerId && networkAdapterName() === "mock") {
    // Test mode without a registered hotspot router: nothing to configure, access is simulated.
    await tx.subscription.update({ where: { id: sub.id }, data: { networkStatus: "SIMULATED_ACTIVE", networkUpdatedAt: new Date() } });
  }
  if (a.payment && updated.currentPeriodStart && updated.currentPeriodEnd) {
    const { invoice } = await createPeriodInvoiceTx(tx, ctx, updated, { start: updated.currentPeriodStart, end: updated.currentPeriodEnd }, action === "activate" ? "activation" : "renewal", { autoAllocate: false, notify: false });
    const due = new D(invoice.balanceDue.toString());
    if (due.gt(0)) await allocateTx(tx, ctx, a.payment.id, invoice.id, D.min(due, new D(a.payment.amount.toString())));
  }
  return { applied: true, subscription: await tx.subscription.findUniqueOrThrow({ where: { id: sub.id } }) };
}

/**
 * Called by the payment pipeline inside the transaction that records a verified hotspot purchase. The payment is kept
 * (as customer credit) but not applied when the plan is gone, its price changed, or the account is suspended.
 */
export async function applyHotspotPurchaseTx(tx: Tx, ctx: ActorContext, attempt: PaymentAttempt, payment: Payment): Promise<{ subscriptionId: string | null }> {
  const keep = async (detail: string) => {
    await tx.paymentAttempt.update({ where: { id: attempt.id }, data: { detail: `Payment received and kept as credit: ${detail}` } });
    return { subscriptionId: null };
  };
  const pkg = attempt.packageId ? await tx.package.findFirst({ where: { id: attempt.packageId, organizationId: attempt.organizationId } }) : null;
  if (!pkg || pkg.status !== "ACTIVE" || pkg.serviceType !== "HOTSPOT") return keep("the plan is no longer sold. Staff will apply it manually.");
  if (!grossPrice(pkg).equals(new D(payment.amount.toString()))) return keep("the plan's price changed before the payment arrived. Staff will apply it manually.");
  const subscriber = await tx.subscriber.findUniqueOrThrow({ where: { id: payment.subscriberId! }, select: { id: true, accountNumber: true } });
  await lockRow(tx, "Subscriber", subscriber.id);
  const grant = await grantPeriodTx(tx, ctx, {
    subscriber,
    pkg,
    routerId: attempt.routerId,
    mac: attempt.clientMac,
    deviceMac: pkg.kind === "DEVICE" ? attempt.clientMac : null,
    idempotencyKey: `hotspot-purchase:${attempt.id}`,
    reason: `Bought on the captive portal (M-Pesa ${payment.providerTransactionId ?? payment.receiptNumber})`,
    payment,
  });
  if (!grant.applied) return keep(grant.reason);
  const tz = (await tx.organization.findUniqueOrThrow({ where: { id: attempt.organizationId }, select: { timezone: true } })).timezone;
  await queueSubscriberNotificationTx(tx, attempt.organizationId, {
    subscriberId: subscriber.id,
    key: "hotspot.purchased",
    vars: { packageName: pkg.name, endDate: grant.subscription.currentPeriodEnd ? formatDateTime(grant.subscription.currentPeriodEnd, tz) : "", receipt: payment.providerTransactionId ?? payment.receiptNumber ?? "" },
    dedupeBase: `hotspot.purchased:${attempt.id}`,
    channels: ["SMS"],
  });
  return { subscriptionId: grant.subscription.id };
}

